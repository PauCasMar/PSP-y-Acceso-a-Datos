public class LibroXmlException extends Exception {

	/**
	 * 
	 */
	private static final long serialVersionUID = 6001683979046952032L;

	public LibroXmlException() {
	}

	public LibroXmlException(String arg0) {
		super(arg0);

	}

	public LibroXmlException(Throwable arg0) {
		super(arg0);

	}

	public LibroXmlException(String arg0, Throwable arg1) {
		super(arg0, arg1);

	}

	public LibroXmlException(String arg0, Throwable arg1, boolean arg2, boolean arg3) {
		super(arg0, arg1, arg2, arg3);

	}

}
